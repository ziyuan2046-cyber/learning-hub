export const textbookRecitations = Object.entries(entries).flatMap(([book, rows]) => {
  const grade = Number(book[0]), volume = book[1];
  const sourceUrl = `https://basic.smartedu.cn/tchMaterial/detail?contentType=assets_document&contentId=${books[book]}&catalogType=tchMaterial&subCatalog=dzjc`;
  const edition = volume === '下' && grade >= 4 ? '平台现行版' : '2022 课标修订版';
  return rows.map(([key, title, page, exercisePage, range, cues]) => ({
    id: `recite-${grade}${volume === '上' ? 'a' : 'b'}-${key}`, grade, volume, title, category: 'text-recitation',
    sourceType: 'text-recitation', sourceLabel: `人教版统编语文 · ${edition} · 必背`,
    excerpt: cues[0], page, exercisePage, range, cues, edition, sourceUrl,
  }));
});

